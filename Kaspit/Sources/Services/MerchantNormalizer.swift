    static func merchantKey(_ raw: String) -> String {
        var s = raw.lowercased()
        // הסרת קידומות נפוצות של סליקה
        for prefix in ["paypal *", "pp*", "google *", "apple.com/bill", "bit ", "פייפאל "] {
            if s.hasPrefix(prefix) { s = String(s.dropFirst(prefix.count)) }
        }
        // גרשיים בקיצורים עבריים (בע"מ, ת"א, קופ"ח) נמחקים בלי רווח כדי לשמור על המילה שלמה
        for quote in ["\"", "'", "\u{05F4}", "\u{05F3}", "\u{201D}", "\u{2019}"] {
            s = s.replacingOccurrences(of: quote, with: "")
        }
        // הסרת ספרות, מקפים וסימנים — משאיר אותיות (עברית/לטינית) ורווחים
        s = s.map { ch -> Character in
            if ch.isLetter || ch.isWhitespace { return ch }
            return " "
        }.reduce(into: "") { $0.append($1) }
        // הסרת מילות רעש נפוצות בשמות עסקים ישראליים
        let noise: Set<String> = ["בעמ", "ltd", "בסניף", "סניף", "תא", "ירושלים", "חיפה", "com", "www"]
        let words = s.split(separator: " ").map(String.init).filter { !noise.contains($0) && !$0.isEmpty }
        return words.joined(separator: " ").trimmingCharacters(in: .whitespaces)
    }


        guard !key.isEmpty else { return nil }
        for entry in knownMerchants where key.contains(entry.match) {
            return Match(displayName: entry.display,
                         categoryName: entry.category,
                         isP2P: entry.category == "ביט / פייבוקס")
        }
        return nil
    }
